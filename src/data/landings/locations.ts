/**
 * Localidades das landing pages de serviço × local.
 *
 * Adicionar uma entrada gera uma página para cada serviço cujo `scope` inclua o
 * `kind` dela. `prep` é a preposição que o português pede antes do nome
 * ("em Moema", "na Vila Mariana", "no Brooklin") e entra no slug, no title e
 * no texto. Nunca escrever "em" fixo em um template.
 *
 * Capital: os 96 distritos oficiais, agrupados pelas 32 subprefeituras, mais
 * bairros conhecidos que não são distrito (Brooklin, Vila Olímpia, Interlagos…),
 * ligados à subprefeitura onde ficam. A zona segue a divisão da Prefeitura:
 * Morumbi (Butantã) e Vila Olímpia/Itaim Bibi (Pinheiros) são Zona Oeste.
 * Fonte: https://www.prefeitura.sp.gov.br/cidade/secretarias/subprefeituras/
 *
 * `note` é opcional e descreve geografia e acesso, nunca eventos já realizados
 * ou uma unidade da YESS no lugar. Sem ela, a página usa os fatos estruturados
 * (subprefeitura, sub-região, distância).
 */
export type LocationKind = 'capital' | 'zona' | 'bairro' | 'metropole' | 'interior' | 'litoral'
export type Region = 'centro' | 'zona-sul' | 'zona-oeste' | 'zona-norte' | 'zona-leste'

export interface Location {
	slug: string
	name: string
	prep: 'em' | 'na' | 'no'
	kind: LocationKind
	/** Zona da capital, para bairros e para a própria zona. */
	region?: Region
	/** Subprefeitura do distrito ou bairro, como a Prefeitura nomeia. */
	subprefeitura?: string
	/** Sub-região com preposição, ex.: "no ABC Paulista", "no Vale do Paraíba". */
	area?: string
	/** Distância aproximada da capital por estrada. */
	distanceKm?: number
	/** Principal acesso rodoviário a partir da capital, com preposição. */
	road?: string
	note?: string
}

type Prep = Location['prep']

const bairro = (
	slug: string,
	name: string,
	prep: Prep,
	region: Region,
	subprefeitura: string,
	note?: string,
): Location => ({ slug, name, prep, kind: 'bairro', region, subprefeitura, note })

const metro = (slug: string, name: string, area: string, note?: string): Location => ({
	slug,
	name,
	prep: 'em',
	kind: 'metropole',
	area,
	note,
})

const city = (
	slug: string,
	name: string,
	distanceKm: number,
	area: string,
	road?: string,
	note?: string,
	kind: LocationKind = 'interior',
): Location => ({ slug, name, prep: 'em', kind, area, distanceKm, road, note })

const coast = (
	slug: string,
	name: string,
	distanceKm: number,
	area: string,
	road?: string,
	note?: string,
) => city(slug, name, distanceKm, area, road, note, 'litoral')

